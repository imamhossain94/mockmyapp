#!/usr/bin/env python3
"""Measure the true screen hole of every frame asset (SVG or PNG) and write
exact geometry (screenRect, frameAspect, screenAspect, cornerRadiusPct) into
assets/frames/manifest.json.

Technique: get an RGBA raster of the frame — SVGs are letterboxed into a
square viewBox over a magenta background and rasterized with QuickLook
(macOS-only); PNGs are read directly since they already carry real alpha —
then the transparent screen hole is measured from pixels. This works
regardless of how the source was authored (Figma masks, Sketch evenodd
rings, generated paths), so manifest geometry can never drift from the
artwork.

Run from repo root:  python3 tool/measure_screen_rects.py
"""

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

from PIL import Image

# SVG rasterisation goes through QuickLook, which only exists on macOS. Rather
# than refuse to run anywhere else, the tool measures what it can: PNG frames
# carry real alpha and need no rasteriser at all, and the SVG frames are all
# generated by `generate_*_frames.py`, which already derives their manifest
# geometry from the same numbers it draws them with. Skipping them elsewhere is
# therefore lossless — the entries this tool would recompute are exactly the
# ones it can still handle.
HAVE_QUICKLOOK = shutil.which("qlmanage") is not None

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "assets", "frames", "manifest.json")
RASTER = 1500  # qlmanage render size for the square SVG wrapper


def rasterize_svg(svg_path):
    """Letterbox an SVG into a square viewBox over magenta and rasterize it
    with QuickLook. Returns (image, scale_to_viewbox_units, pad_x, pad_y,
    is_hole) where is_hole(px) tests for the magenta background."""
    svg = open(svg_path, encoding="utf-8").read()
    m = re.search(r'viewBox="([-\d\. ]+)"', svg)
    _, _, W, H = (float(v) for v in m.group(1).split())
    side = max(W, H)
    pad_x, pad_y = (side - W) / 2, (side - H) / 2

    inner = re.sub(r"^.*?<svg[^>]*>", "", svg, count=1, flags=re.S)
    inner = inner.rsplit("</svg>", 1)[0]
    wrapped = (
        f'<svg xmlns="http://www.w3.org/2000/svg" '
        f'xmlns:xlink="http://www.w3.org/1999/xlink" '
        f'width="{side}px" height="{side}px" '
        f'viewBox="{-pad_x} {-pad_y} {side} {side}">'
        f'<rect x="{-pad_x}" y="{-pad_y}" width="{side}" height="{side}" '
        f'fill="#FF00FF"/>{inner}</svg>'
    )

    with tempfile.TemporaryDirectory() as tmp:
        wrapped_path = os.path.join(tmp, "wrapped.svg")
        with open(wrapped_path, "w") as f:
            f.write(wrapped)
        # qlmanage occasionally exits 0 without writing the thumbnail
        png_path = os.path.join(tmp, "wrapped.svg.png")
        for attempt in range(4):
            subprocess.run(
                ["qlmanage", "-t", "-s", str(RASTER), "-o", tmp, wrapped_path],
                capture_output=True, check=True)
            if os.path.exists(png_path):
                break
            time.sleep(0.5)
        img = Image.open(png_path).convert("RGB")

    scale = side / img.width

    def is_hole(px):
        r, g, b = px[:3]
        return r > 200 and g < 60 and b > 200

    return img, scale, pad_x, pad_y, is_hole, W, H


def load_png(png_path):
    """PNGs already carry real alpha, so no magenta wrapping is needed —
    the hole is wherever alpha is (near-)zero, in native pixel units."""
    img = Image.open(png_path).convert("RGBA")
    W, H = img.size

    def is_hole(px):
        return px[3] < 16

    return img, 1.0, 0.0, 0.0, is_hole, float(W), float(H)


def measure(asset_path):
    """Return (frame_w, frame_h, hole_x, hole_y, hole_w, hole_h, corner_r)
    in the asset's native coordinate units (SVG viewBox units, or PNG px)."""
    if asset_path.lower().endswith(".svg"):
        img, scale, pad_x, pad_y, is_hole, W, H = rasterize_svg(asset_path)
    else:
        img, scale, pad_x, pad_y, is_hole, W, H = load_png(asset_path)

    IW, IH = img.width, img.height
    px = img.load()
    cx, cy = IW // 2, IH // 2

    # Horizontal span of the hole along the image center row.
    if not is_hole(px[cx, cy]):
        raise RuntimeError(f"center pixel is not screen hole in {asset_path}")
    x0 = x1 = cx
    while x0 > 0 and is_hole(px[x0 - 1, cy]):
        x0 -= 1
    while x1 < IW - 1 and is_hole(px[x1 + 1, cy]):
        x1 += 1

    # Vertical span at quarter width — clear of center punch holes/islands.
    qx = x0 + (x1 - x0) // 4
    y0 = y1 = cy
    while y0 > 0 and is_hole(px[qx, y0 - 1]):
        y0 -= 1
    while y1 < IH - 1 and is_hole(px[qx, y1 + 1]):
        y1 += 1

    # Corner radius of the VISIBLE opening: walk left from inside the screen
    # so detached transparent slivers (square mask corners poking past the
    # rounded body) can't fake a zero radius. r = first row whose contiguous
    # run reaches the left edge. Slightly over-rounded for AA safety — extra
    # rounding tucks under the bezel art, while too little would leak color
    # past the body corners.
    r_rows = 0
    for dy in range(int(IH * 0.15)):
        row_y = y0 + dy
        edge = qx
        while edge > x0 and is_hole(px[edge - 1, row_y]):
            edge -= 1
        if edge - x0 <= max(2, IW // 500):
            r_rows = dy
            break
    r_rows = r_rows * 1.1 + IW / 750

    to_vb = lambda v: v * scale
    return (
        W, H,
        to_vb(x0) - pad_x, to_vb(y0) - pad_y,
        to_vb(x1 - x0 + 1), to_vb(y1 - y0 + 1),
        to_vb(r_rows),
    )


def main():
    with open(MANIFEST, encoding="utf-8") as f:
        manifest = json.load(f)

    measured = skipped = 0
    for device in manifest["devices"]:
        asset = device["variants"][0]["asset"]
        path = os.path.join(ROOT, asset)
        if not os.path.exists(path):
            print(f"SKIP {device['id']}: missing {asset}", file=sys.stderr)
            continue
        if asset.lower().endswith(".svg") and not HAVE_QUICKLOOK:
            skipped += 1
            continue
        W, H, hx, hy, hw, hh, r = measure(path)
        measured += 1
        device["frameAspect"] = round(W / H, 4)
        device["screenAspect"] = round(hw / hh, 4)
        device["screenRect"] = {
            "x": round(hx / W, 4),
            "y": round(hy / H, 4),
            "w": round(hw / W, 4),
            "h": round(hh / H, 4),
        }
        device["cornerRadiusPct"] = round(r / hw, 4)
        print(f"{device['id']:32s} rect=({hx / W:.4f},{hy / H:.4f},"
              f"{hw / W:.4f},{hh / H:.4f}) rPct={r / hw:.4f}")

    with open(MANIFEST, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    print(f"\nupdated {os.path.relpath(MANIFEST, ROOT)}  "
          f"({measured} measured, {skipped} SVG skipped — no QuickLook)")


if __name__ == "__main__":
    main()
