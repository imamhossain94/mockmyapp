  List<Widget> _fieldTiles(Project project, CopyStore store, String locale) {
    final fields = project.storeCopy.fieldsOf(store, locale);
    final issues = lintCopy(store, fields, appName: _appNameOf(project));
    return [
      for (final spec in store.allFields) ...[
        Builder(
          builder: (context) {
            final key = _key(store, locale, spec.id);
            final controller = _controllerFor(project, store, locale, spec);
            final writtenBy = _writtenBy[key];
            return StoreCopyFieldTile(
              spec: spec,
              controller: controller,
              issues: [
                for (final i in issues)
                  if (i.field == spec.id) i,
              ],
              writtenBy: switch (writtenBy) {
                null => null,
                AiEngine.phrasebook => 'Built-in suggestion',
                final e => 'Written by ${e.label}',
              },
              onChanged: (text) => _onTyped(store, locale, spec.id, text),
              onCopy: () => _copy(spec.label.toLowerCase(), controller.text),
              regenerating: _regenerating == spec.id,
              regenerateTooltip: 'Regenerate · On this device',
              onRegenerate: _drafting || _regenerating != null
                  ? null
                  : () => _draft(field: spec.id),
              onFix: (fixed) {
                _projects.updateStoreCopy(
                  widget.projectId,
                  (c) => c.withText(store, locale, spec.id, fixed),
                );
                _syncControllers();
                setState(() {});
              },
            );
          },
        ),
        SizedBox(height: StudioSpace.l),
      ],
    ];
  }

  Widget _translatePanel(Project project, CopyStore store) {
    final s = context.studio;
    final from = project.defaultLanguage;
    final others = [
      for (final l in project.languages)
        if (l != from) l,
    ];
    if (others.isEmpty) {
      return StudioPanel(
        key: const ValueKey('translate-panel'),
        title: 'Translate',
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Text(
              'Add a language to translate this copy into. The project’s '
              'screenshots get it too.',
              style: StudioText.body(context).copyWith(color: s.textSecondary),
            ),
            SizedBox(height: StudioSpace.l),
            StudioButton(
              key: const ValueKey('add-language'),
              label: 'Add a language',
              icon: StudioIcons.add,
              fullWidth: true,
              onPressed: () => _addLanguage(project),
            ),
          ],
        ),
      );
    }
    final targets = _targetsOf(project);
    final source = project.storeCopy.fieldsOf(store, from);
    return StudioPanel(
      key: const ValueKey('translate-panel'),
      title: 'Translate',
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Text(
            'From ${localeFor(from).name} into:',
            style: StudioText.body(context).copyWith(color: s.textSecondary),
          ),
          SizedBox(height: StudioSpace.s),
          Wrap(
            spacing: StudioSpace.s,
            runSpacing: StudioSpace.s,
            children: [
              for (final l in others)
                StudioChip(
                  label: localeFor(l).name,
                  selected: targets.contains(l),
                  onTap: _translating
                      ? null
                      : () => setState(() {
                          if (!_translateToTouched) {
                            _translateTo
                              ..clear()
                              ..addAll(others);
                            _translateToTouched = true;
                          }
                          if (!_translateTo.remove(l)) _translateTo.add(l);
                        }),
                ),
            ],
          ),
          SizedBox(height: StudioSpace.l),
          Text(
            'With this device’s translator. Language packs download once '
            'when needed.',
            key: const ValueKey('translate-line'),
            style: StudioText.caption(context).copyWith(color: s.textSecondary),
          ),
          SizedBox(height: StudioSpace.l),
          StudioButton(
            key: const ValueKey('translate'),
            label: 'Translate · On this device',
            icon: StudioIcons.web,
            fullWidth: true,
            loading: _translating,
            onPressed: targets.isEmpty || source.isEmpty ? null : _translate,
          ),
          if (source.isEmpty) ...[
            SizedBox(height: StudioSpace.s),
            Text(
              'Write the ${localeFor(from).name} copy first; translations '
              'start from it.',
              style: StudioText.caption(
                context,
              ).copyWith(color: s.textSecondary),
            ),
          ],
          for (final MapEntry(key: l, value: (state, why)) in _progress.entries)
            Padding(
              padding: EdgeInsets.only(top: StudioSpace.s),
              child: Row(
                children: [
                  SizedBox.square(
                    dimension: 16,
                    child: switch (state) {
                      _Progress.queued || _Progress.working => const Center(
                        child: SizedBox.square(
                          dimension: 12,
                          child: CircularProgressIndicator(strokeWidth: 2),
                        ),
                      ),
                      _Progress.done => StudioIcon(
                        StudioIcons.check,
                        size: 12,
                        color: s.successText,
                      ),
                      _Progress.failed => StudioIcon(
                        StudioIcons.warning,
                        size: 12,
                        color: s.warningText,
                      ),
                    },
                  ),
                  SizedBox(width: StudioSpace.m),
                  Expanded(
                    child: Text(
                      '${localeFor(l).name} · ${switch (state) {
                        _Progress.queued => 'Queued',
                        _Progress.working => 'Translating…',
                        _Progress.done => 'Done',
                        _Progress.failed => why ?? 'Not translated',
                      }}',
                      style: StudioText.caption(
                        context,
                      ).copyWith(color: s.textPrimary),
                    ),
                  ),
                ],
              ),
            ),
        ],
      ),
    );
  }
