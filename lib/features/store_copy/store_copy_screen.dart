  StudioIconData _storeIcon(CopyStore store) => switch (store) {
    CopyStore.appStore || CopyStore.macAppStore => StudioIcons.platformApple,
    CopyStore.playStore => StudioIcons.platformPlayStore,
    CopyStore.microsoftStore => StudioIcons.desktop,
    CopyStore.galaxyStore => StudioIcons.phone,
    CopyStore.huaweiAppGallery => StudioIcons.phone,
    CopyStore.amazonAppstore => StudioIcons.tablet,
  };

