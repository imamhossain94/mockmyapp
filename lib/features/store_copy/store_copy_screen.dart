/// The listing's words outside the screenshots — name, subtitle, keywords,
/// descriptions, what's new, screenshot alt text — for every store the
/// project ships to, in every language it is made in.
///
/// One store and one language at a time: a field per row with a counter in
/// the store's own unit (bytes for Apple's keywords and Samsung) and the
/// review checks under it, each with its fix. "Draft with AI" writes them
/// from the project's brief, on this device — its own model where there is
/// one, the built-in rules where there is not — and every field can be
/// written again on its own, edited or copied. "Translate" fills the
/// project's other languages with the device's translator. Everything lands in the project, so it is
/// saved, backed up, and exported in the fastlane ZIP.
class StoreCopyScreen extends ConsumerStatefulWidget {
  const StoreCopyScreen({super.key, required this.projectId});

  final String projectId;

  @override
  ConsumerState<StoreCopyScreen> createState() => _StoreCopyScreenState();
}

/// What a translation run has got to, per language.
enum _Progress { queued, working, done, failed }

class _StoreCopyScreenState extends ConsumerState<StoreCopyScreen>
    with ProjectActions<StoreCopyScreen> {
  @override
  String get projectId => widget.projectId;

  @override
  void onActiveTargetChanged(String? subId) {}

  /// The store and language the person picked; null until they pick.
  CopyStore? _storeChoice;
  String? _localeChoice;

  /// Stores opened from "More stores" this visit, before they hold any copy.
  final _openedStores = <CopyStore>{};

  AiEngine _deviceEngine = AiEngine.phrasebook;

  /// One controller per store, language and field, made as the field shows.
  final _controllers = <String, TextEditingController>{};

  /// Who wrote each field this visit. Not saved: it describes a result just
  /// seen.
  final _writtenBy = <String, AiEngine>{};

  /// How many times each field has been regenerated by the rules, so the
  /// next press moves to their next alternative.
  final _variants = <String, int>{};

  bool _drafting = false;
  String? _regenerating;
  String? _notice;
  StudioNoticeTone _noticeTone = StudioNoticeTone.info;

  bool _translating = false;
  final _translateTo = <String>{};
  bool _translateToTouched = false;
  final _progress = <String, (_Progress, String?)>{};

  @override
  void initState() {
    super.initState();
    DeviceCopyWriter(ref.read(textCompleterProvider)).engine().then((engine) {
      if (mounted) setState(() => _deviceEngine = engine);
    });
  }

  @override
  void dispose() {
    for (final c in _controllers.values) {
      c.dispose();
    }
    super.dispose();
  }

  ProjectStore get _projects => ref.read(projectStoreProvider.notifier);

  Project? get _project => ref
      .read(projectStoreProvider)
      .where((p) => p.id == widget.projectId)
      .firstOrNull;

  // ---------------------------------------------------------------------------
  // What is showing
  // ---------------------------------------------------------------------------

  /// The stores this project's copy is written for: Apple's and Google's
  /// always, any other store a target points at or that already has copy, and
  /// any opened this visit — offered stores only.
  List<CopyStore> _storesOf(Project p) {
    final targeted = {for (final sub in p.subProjects) sub.target.store};
    return [
      for (final s in CopyStore.values)
        if (s.offered &&
            (s == CopyStore.appStore ||
                s == CopyStore.playStore ||
                targeted.contains(s.storeKind) ||
                p.storeCopy.has(s) ||
                _openedStores.contains(s)))
          s,
    ];
  }

  CopyStore _storeOf(Project p) {
    final shown = _storesOf(p);
    if (_storeChoice case final choice? when shown.contains(choice)) {
      return choice;
    }
    // The store the project's first set is for, when it has copy here.
    final first = p.subProjects.firstOrNull?.target.store;
    return shown.where((s) => s.storeKind == first).firstOrNull ?? shown.first;
  }

  /// The project's languages, then any other language that has copy.
  List<String> _localesOf(Project p) => [
    ...p.languages,
    for (final l in p.storeCopy.locales)
      if (!p.languages.contains(l)) l,
  ];

  String _localeOf(Project p) {
    final locales = _localesOf(p);
    final choice = _localeChoice;
    return choice != null && locales.contains(choice)
        ? choice
        : p.defaultLanguage;
  }

  static String _key(CopyStore store, String locale, String field) =>
      '${store.name}/$locale/$field';

  TextEditingController _controllerFor(
    Project p,
    CopyStore store,
    String locale,
    CopyFieldSpec field,
  ) => _controllers.putIfAbsent(
    _key(store, locale, field.id),
    () =>
        TextEditingController(text: p.storeCopy.text(store, locale, field.id)),
  );

  /// Every controller brought back in line with the project, after something
  /// other than typing changed it — a draft, a translation, an Undo, a fix.
  void _syncControllers() {
    final p = _project;
    if (p == null) return;
    for (final MapEntry(:key, value: controller) in _controllers.entries) {
      final [store, locale, field] = key.split('/');
      final text = p.storeCopy.text(CopyStore.byName(store)!, locale, field);
      if (controller.text != text) controller.text = text;
    }
  }

  String _appNameOf(Project p) =>
      p.brief.appName.trim().isNotEmpty ? p.brief.appName.trim() : p.name;

  /// The headlines of the project's screens, in order — what the drafts
  /// describe for Play's alt text, and write from when the brief is empty.
  List<String> _captionsOf(Project p, CopyStore store) {
    final sets = [
      ...p.subProjects.where((s) => s.target.store == store.storeKind),
      ...p.subProjects,
    ];
    final set = sets.where((s) => s.screens.isNotEmpty).firstOrNull;
    return [
      for (final screen in set?.screens ?? const [])
        if (screen.caption case final caption? when caption.enabled)
          caption.text.replaceAll('\n', ' ').trim(),
    ];
  }

  DraftSource _sourceOf(Project p, CopyStore store) => DraftSource.from(
    p.brief,
    projectName: p.name,
    captions: _captionsOf(p, store),
  );

  // ---------------------------------------------------------------------------
  // Engines
  // ---------------------------------------------------------------------------

  String get _deviceLabel => _deviceEngine == AiEngine.phrasebook
      ? 'Built-in suggestions'
      : _deviceEngine.label;

  // ---------------------------------------------------------------------------
  // Writing
  // ---------------------------------------------------------------------------

  void _onTyped(CopyStore store, String locale, String field, String text) {
    _projects.updateStoreCopy(
      widget.projectId,
      (c) => c.withText(store, locale, field, text),
    );
    setState(() {});
  }

  /// Puts [fields] in the project and says so, with an Undo that puts back
  /// what was there before.
  void _apply(
    CopyStore store,
    String locale,
    Map<String, String> fields, {
    required AiEngine engine,
    String? what,
  }) {
    final before = _project?.storeCopy ?? StoreCopy.empty;
    final previous = {
      for (final id in fields.keys)
        _key(store, locale, id): _writtenBy[_key(store, locale, id)],
    };
    _projects.updateStoreCopy(
      widget.projectId,
      (c) => c.withFields(store, locale, fields),
    );
    for (final id in fields.keys) {
      _writtenBy[_key(store, locale, id)] = engine;
    }
    _syncControllers();
    setState(() {});
    final count = fields.length;
    showStudioSnack(
      context,
      what ??
          'Drafted $count ${count == 1 ? 'field' : 'fields'} '
              '${engine == AiEngine.phrasebook ? 'with the built-in suggestions' : 'with ${engine.label}'}',
      actionLabel: 'Undo',
      onAction: () {
        _projects.setStoreCopy(widget.projectId, before);
        // Who wrote each field goes back too.
        for (final MapEntry(:key, value: engine) in previous.entries) {
          if (engine == null) {
            _writtenBy.remove(key);
          } else {
            _writtenBy[key] = engine;
          }
        }
        _syncControllers();
        if (mounted) setState(() {});
      },
    );
  }

  /// Says [message] in the draft panel — and, when [toast], as a toast too:
  /// a field's Regenerate is pressed far from the panel on a phone, and a
  /// reason said only where nobody is looking is a reason not said.
  void _say(
    String message, {
    StudioNoticeTone tone = StudioNoticeTone.warning,
    bool toast = false,
  }) {
    setState(() {
      _notice = message;
      _noticeTone = tone;
    });
    if (toast) {
      showStudioSnack(
        context,
        message,
        icon: tone == StudioNoticeTone.info
            ? StudioIcons.info
            : StudioIcons.warning,
      );
    }
  }

  /// Drafts every field of the store on show, or just [field].
  Future<void> _draft({String? field}) async {
    final p = _project;
    if (p == null || _drafting || _regenerating != null) return;
    final store = _storeOf(p);
    final locale = _localeOf(p);
    if (field == null && p.storeCopy.fieldsOf(store, locale).isNotEmpty) {
      // Somebody's words are never written over without asking; Undo is
      // there too, but a toast is easy to miss.
      final go = await showStudioConfirm(
        context,
        title: 'Replace the copy?',
        message:
            'This writes every ${store.label} field in '
            '${localeFor(locale).name} again, over what is there now. Undo '
            'puts it back.',
        confirmLabel: 'Replace',
        icon: StudioIcons.storeCopy,
      );
      if (!go || !mounted) return;
    }
    setState(() {
      _notice = null;
      if (field == null) {
        _drafting = true;
      } else {
        _regenerating = field;
      }
    });
    try {
      await _draftOnDevice(p, store, locale, field: field);
    } finally {
      if (mounted) {
        setState(() {
          _drafting = false;
          _regenerating = null;
        });
      }
    }
  }

  Future<void> _draftOnDevice(
    Project p,
    CopyStore store,
    String locale, {
    String? field,
  }) async {
    final key = field == null ? null : _key(store, locale, field);
    final variant = key == null
        ? 0
        : (_variants[key] = (_variants[key] ?? 0) + 1);
    try {
      final result = await DeviceCopyWriter(ref.read(textCompleterProvider))
          .draft(
            store,
            _sourceOf(p, store),
            language: locale,
            inBriefLanguage: locale == p.defaultLanguage,
            tone: p.brief.tone,
            only: field == null ? null : {field},
            variant: variant,
          );
      if (!mounted) return;
      if (result.fields.isEmpty) {
        _say(
          'There was nothing to draft from. Write the brief first.',
          toast: field != null,
        );
        return;
      }
      _apply(store, locale, result.fields, engine: result.engine);
      if (result.note case final note?) {
        _say(note, tone: StudioNoticeTone.info);
      }
    } on OnDeviceAiException catch (error) {
      if (mounted) {
        _say(error.message, tone: StudioNoticeTone.info, toast: field != null);
      }
    }
  }

  Future<void> _copy(String label, String text) async {
    await Clipboard.setData(ClipboardData(text: text));
    if (mounted) showStudioSnack(context, 'Copied the $label');
  }

  Future<void> _copyAll(Project p) async {
    final store = _storeOf(p);
    final locale = _localeOf(p);
    final fields = p.storeCopy.fieldsOf(store, locale);
    if (fields.isEmpty) {
      showStudioSnack(context, 'Nothing to copy yet', icon: StudioIcons.info);
      return;
    }
    await Clipboard.setData(
      ClipboardData(text: copyAllText(store, locale, fields)),
    );
    if (mounted) {
      showStudioSnack(
        context,
        'Copied all ${store.label} text in ${localeFor(locale).name}',
      );
    }
  }

  Future<void> _editBrief(Project p) async {
    final next = await showBriefSheet(
      context,
      brief: p.brief,
      projectName: p.name,
    );
    if (next == null || !mounted) return;
    _projects.setListingBrief(widget.projectId, next);
    showStudioSnack(context, 'Brief saved');
  }

  Future<void> _addLanguage(Project p) async {
    final code = await showAddLanguageSheet(context, existing: p.languages);
    if (code == null || !mounted) return;
    _projects.setLanguages(widget.projectId, [...p.languages, code]);
    setState(() {
      _localeChoice = code;
      _translateTo.add(code);
    });
  }

  // ---------------------------------------------------------------------------
  // Translating
  // ---------------------------------------------------------------------------

  List<String> _targetsOf(Project p) {
    final others = [
      for (final l in p.languages)
        if (l != p.defaultLanguage) l,
    ];
    if (!_translateToTouched) return others;
    return [
      for (final l in others)
        if (_translateTo.contains(l)) l,
    ];
  }

  Future<void> _translate() async {
    final p = _project;
    if (p == null || _translating) return;
    final store = _storeOf(p);
    final from = p.defaultLanguage;
    final source = p.storeCopy.fieldsOf(store, from);
    final targets = _targetsOf(p);
    if (source.isEmpty) {
      _say(
        'Write the ${localeFor(from).name} copy first; translations start '
        'from it.',
      );
      return;
    }
    if (targets.isEmpty) {
      _say('Pick a language to translate into.');
      return;
    }
    // A translation somebody wrote or corrected is theirs: replacing it is
    // asked first, and Undo puts it back afterwards.
    final existing = [
      for (final t in targets)
        if (p.storeCopy.has(store, t)) localeFor(t).name,
    ];
    if (existing.isNotEmpty) {
      final go = await showStudioConfirm(
        context,
        title: 'Replace the translations?',
        message: '${_replaceSentence(existing, store)} Undo puts it back.',
        confirmLabel: 'Translate',
        icon: StudioIcons.web,
      );
      if (!go || !mounted) return;
    }
    _beforeTranslation = p.storeCopy;
    setState(() {
      _notice = null;
      _translating = true;
      _progress
        ..clear()
        ..addAll({for (final t in targets) t: (_Progress.queued, null)});
    });
    try {
      await _translateOnDevice(p, store, from, source, targets);
    } finally {
      if (mounted) setState(() => _translating = false);
    }
  }

  Future<void> _translateOnDevice(
    Project p,
    CopyStore store,
    String from,
    Map<String, String> source,
    List<String> targets,
  ) async {
    final translator = DeviceCopyTranslator(ref.read(translatorProvider));
    var done = 0;
    for (final to in targets) {
      if (!mounted) return;
      final status = await translator.status(from: from, to: to);
      if (!status.usable) {
        setState(
          () => _progress[to] = (
            _Progress.failed,
            status.reason ?? 'Not available on this device',
          ),
        );
        continue;
      }
      setState(() => _progress[to] = (_Progress.working, null));
      try {
        final out = await translator.translate(
          store,
          source,
          from: from,
          to: to,
          appName: _appNameOf(p),
        );
        if (!mounted) return;
        _projects.updateStoreCopy(
          widget.projectId,
          (c) => c.withFields(store, to, out),
        );
        for (final id in out.keys) {
          _writtenBy[_key(store, to, id)] = status.engine;
        }
        done++;
        setState(() => _progress[to] = (_Progress.done, null));
      } on OnDeviceAiException catch (error) {
        if (mounted) {
          setState(() => _progress[to] = (_Progress.failed, error.message));
        }
      }
    }
    _syncControllers();
    if (!mounted) return;
    setState(() {});
    if (done > 0) {
      showStudioSnack(
        context,
        'Translated into $done ${done == 1 ? 'language' : 'languages'}. Read '
        'them over before you ship.',
        actionLabel: 'Undo',
        onAction: _undoTranslation,
      );
    } else {
      _say("This device couldn't translate into those languages.");
    }
  }

  /// The project's copy before the last translation, for its Undo.
  StoreCopy? _beforeTranslation;

  void _undoTranslation() {
    final before = _beforeTranslation;
    if (before == null) return;
    _projects.setStoreCopy(widget.projectId, before);
    _syncControllers();
    if (mounted) setState(() {});
  }

  /// "German already has App Store copy; translating replaces it."
  static String _replaceSentence(List<String> names, CopyStore store) {
    final who = names.length == 1
        ? names.single
        : '${names.take(names.length - 1).join(', ')} and ${names.last}';
    return '$who already ${names.length == 1 ? 'has' : 'have'} ${store.label} '
        'copy; translating replaces it.';
  }

